begin;

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 2 and 120),
  contact_email text,
  address text,
  owner_user_id uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'owner' check (role in ('owner','admin','dispatcher','driver','viewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id),
  unique (user_id)
);

create table if not exists public.vehicles (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  id text not null,
  plate text not null,
  vehicle_type text not null default '',
  capacity text not null default '',
  status text not null default 'Disponible',
  latitude double precision,
  longitude double precision,
  location_mode text not null default 'demo',
  last_seen timestamptz,
  driver_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (organization_id, id),
  check (latitude is null or latitude between -90 and 90),
  check (longitude is null or longitude between -180 and 180),
  check (status in ('Disponible','En operación','En mantenimiento')),
  check (location_mode in ('demo','real','last','sim','manual','cloud'))
);

create table if not exists public.drivers (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  id text not null,
  name text not null,
  phone text not null default '',
  license_type text not null default '',
  status text not null default 'Disponible',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (organization_id, id),
  check (status in ('Disponible','En ruta','No disponible'))
);

create table if not exists public.deliveries (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  id text not null,
  recipient text not null,
  phone text not null default '',
  address text not null,
  latitude double precision,
  longitude double precision,
  priority text not null default 'Media',
  status text not null default 'Pendiente',
  vehicle_id text,
  driver_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (organization_id, id),
  check (latitude is null or latitude between -90 and 90),
  check (longitude is null or longitude between -180 and 180),
  check (priority in ('Alta','Media','Baja')),
  check (status in ('Pendiente','En ruta','Entregada'))
);

create table if not exists public.gps_positions (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  vehicle_id text not null,
  user_id uuid not null references auth.users(id) on delete restrict,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);

create index if not exists idx_org_members_user on public.organization_members(user_id);
create index if not exists idx_vehicles_org_status on public.vehicles(organization_id, status);
create index if not exists idx_drivers_org_status on public.drivers(organization_id, status);
create index if not exists idx_deliveries_org_status on public.deliveries(organization_id, status);
create index if not exists idx_deliveries_org_created on public.deliveries(organization_id, created_at desc);
create index if not exists idx_gps_org_vehicle_time on public.gps_positions(organization_id, vehicle_id, recorded_at desc);

create or replace function public.current_org_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select om.organization_id
  from public.organization_members om
  where om.user_id = auth.uid()
  limit 1;
$$;

create or replace function public.current_org_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select om.role
  from public.organization_members om
  where om.user_id = auth.uid()
  limit 1;
$$;

create or replace function public.is_org_operator()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_org_role() in ('owner','admin','dispatcher'), false);
$$;

create or replace function public.create_company_workspace(
  p_name text default null,
  p_email text default null,
  p_address text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_org_id uuid;
  v_name text;
  v_full_name text;
  v_email text;
begin
  if v_user_id is null then
    raise exception 'Debes iniciar sesión para crear un espacio empresarial.';
  end if;

  select om.organization_id into v_org_id
  from public.organization_members om
  where om.user_id = v_user_id
  limit 1;

  if v_org_id is not null then
    return v_org_id;
  end if;

  v_name := coalesce(nullif(trim(p_name), ''), nullif(trim(auth.jwt() -> 'user_metadata' ->> 'company_name'), ''), 'Mi empresa');
  v_full_name := coalesce(nullif(trim(auth.jwt() -> 'user_metadata' ->> 'full_name'), ''), 'Administrador');
  v_email := coalesce(nullif(trim(p_email), ''), auth.jwt() ->> 'email');

  insert into public.organizations(name, contact_email, address, owner_user_id)
  values (v_name, v_email, nullif(trim(p_address), ''), v_user_id)
  returning id into v_org_id;

  insert into public.organization_members(organization_id, user_id, full_name, role)
  values (v_org_id, v_user_id, v_full_name, 'owner');

  return v_org_id;
end;
$$;

alter table public.organizations enable row level security;
alter table public.organization_members enable row level security;
alter table public.vehicles enable row level security;
alter table public.drivers enable row level security;
alter table public.deliveries enable row level security;
alter table public.gps_positions enable row level security;

drop policy if exists org_select_member on public.organizations;
create policy org_select_member on public.organizations
for select to authenticated
using (id = public.current_org_id());

drop policy if exists org_update_operator on public.organizations;
create policy org_update_operator on public.organizations
for update to authenticated
using (id = public.current_org_id() and public.current_org_role() in ('owner','admin'))
with check (id = public.current_org_id() and public.current_org_role() in ('owner','admin'));

drop policy if exists members_select_same_org on public.organization_members;
create policy members_select_same_org on public.organization_members
for select to authenticated
using (user_id = auth.uid() or organization_id = public.current_org_id());

drop policy if exists vehicles_select_org on public.vehicles;
create policy vehicles_select_org on public.vehicles for select to authenticated
using (organization_id = public.current_org_id());
drop policy if exists vehicles_write_org on public.vehicles;
create policy vehicles_write_org on public.vehicles for all to authenticated
using (organization_id = public.current_org_id() and public.is_org_operator())
with check (organization_id = public.current_org_id() and public.is_org_operator());

drop policy if exists drivers_select_org on public.drivers;
create policy drivers_select_org on public.drivers for select to authenticated
using (organization_id = public.current_org_id());
drop policy if exists drivers_write_org on public.drivers;
create policy drivers_write_org on public.drivers for all to authenticated
using (organization_id = public.current_org_id() and public.is_org_operator())
with check (organization_id = public.current_org_id() and public.is_org_operator());

drop policy if exists deliveries_select_org on public.deliveries;
create policy deliveries_select_org on public.deliveries for select to authenticated
using (organization_id = public.current_org_id());
drop policy if exists deliveries_write_org on public.deliveries;
create policy deliveries_write_org on public.deliveries for all to authenticated
using (organization_id = public.current_org_id() and public.is_org_operator())
with check (organization_id = public.current_org_id() and public.is_org_operator());

drop policy if exists gps_select_org on public.gps_positions;
create policy gps_select_org on public.gps_positions for select to authenticated
using (organization_id = public.current_org_id());
drop policy if exists gps_insert_member on public.gps_positions;
create policy gps_insert_member on public.gps_positions for insert to authenticated
with check (organization_id = public.current_org_id() and user_id = auth.uid());

grant usage on schema public to authenticated;
grant select, update on public.organizations to authenticated;
grant select on public.organization_members to authenticated;
grant select, insert, update, delete on public.vehicles, public.drivers, public.deliveries to authenticated;
grant select, insert on public.gps_positions to authenticated;
grant usage, select on sequence public.gps_positions_id_seq to authenticated;
revoke all on function public.current_org_id() from public;
revoke all on function public.current_org_role() from public;
revoke all on function public.is_org_operator() from public;
revoke all on function public.create_company_workspace(text,text,text) from public;
grant execute on function public.current_org_id() to authenticated;
grant execute on function public.current_org_role() to authenticated;
grant execute on function public.is_org_operator() to authenticated;
grant execute on function public.create_company_workspace(text,text,text) to authenticated;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'vehicles') then
    alter publication supabase_realtime add table public.vehicles;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'drivers') then
    alter publication supabase_realtime add table public.drivers;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'deliveries') then
    alter publication supabase_realtime add table public.deliveries;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'gps_positions') then
    alter publication supabase_realtime add table public.gps_positions;
  end if;
end $$;

commit;
