    select 1
    from pg_publication
    where pubname = 'supabase_realtime'
  ) then
    foreach v_table in array array['delivery_financials','financial_expenses','route_runs','driver_incidents']
    loop
      if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = v_table
      ) then
        execute format('alter publication supabase_realtime add table public.%I',v_table);
      end if;
    end loop;
  end if;
end;
$$;

