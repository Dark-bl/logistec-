create or replace function public.is_platform_superadmin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.platform_superadmins p
    where p.user_id = auth.uid()
      and p.enabled = true
  );
$$;

create or replace function public.get_platform_dashboard()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
begin
  if not public.is_platform_superadmin() then
    raise exception 'Acceso reservado al superadministrador de plataforma';
  end if;

  select jsonb_build_object(
    'organization_count', (select count(*) from public.organizations),
    'member_count', (select count(*) from public.organization_members),
    'vehicle_count', (select count(*) from public.vehicles),
    'delivery_count', (select count(*) from public.deliveries),
    'pending_count', (select count(*) from public.deliveries where status in ('Pendiente','En ruta')),
    'completed_count', (select count(*) from public.deliveries where status = 'Entregada'),
    'revenue_total', (select coalesce(sum(revenue_amount),0) from public.delivery_financials),
    'expense_total', (select coalesce(sum(amount),0) from public.financial_expenses),
    'organizations', (
      select coalesce(jsonb_agg(x.item order by x.created_at desc), '[]'::jsonb)
      from (
        select
          o.created_at,
          jsonb_build_object(
            'id',o.id,
            'name',o.name,
            'created_at',o.created_at,
            'member_count',(select count(*) from public.organization_members m where m.organization_id=o.id),
            'vehicle_count',(select count(*) from public.vehicles v where v.organization_id=o.id),
            'delivery_count',(select count(*) from public.deliveries d where d.organization_id=o.id)
          ) as item
        from public.organizations o
        order by o.created_at desc
        limit 100
      ) x
    )
  ) into v_result;

  return v_result;
end;
$$;

create or replace function public.driver_update_delivery_status(
  p_delivery_id text,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_org_id uuid;
  v_driver_id text;
  v_row public.deliveries%rowtype;
begin
  v_org_id := public.current_org_id();
  if auth.uid() is null or v_org_id is null or public.current_user_role() <> 'driver' then
    raise exception 'Acceso reservado a conductores autenticados';
  end if;

  select d.id into v_driver_id
  from public.drivers d
  where d.organization_id = v_org_id
    and d.user_id = auth.uid()
  limit 1;

  if v_driver_id is null then
    raise exception 'La cuenta no está vinculada a un perfil de conductor';
  end if;

  if coalesce(p_status,'') not in ('En ruta','Entregada') then
    raise exception 'Estado solicitado no permitido';
  end if;

  update public.deliveries d
  set status = p_status,
      updated_at = now()
  where d.organization_id = v_org_id
    and d.id = p_delivery_id
    and d.driver_id = v_driver_id
    and (
      (d.status = 'Pendiente' and p_status = 'En ruta')
      or (d.status = 'En ruta' and p_status = 'Entregada')
    )
  returning d.* into v_row;

  if not found then
    raise exception 'La entrega no está asignada a esta cuenta o el cambio de estado no está permitido';
  end if;

  return jsonb_build_object(
    'id',v_row.id,
    'status',v_row.status,
    'updated_at',v_row.updated_at
  );
end;
$$;

create or replace function public.driver_report_incident(
  p_delivery_id text,
  p_incident_type text,
  p_details text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_org_id uuid;
  v_driver_id text;
  v_incident_id bigint;
  v_type text;
begin
  v_org_id := public.current_org_id();
  if auth.uid() is null or v_org_id is null or public.current_user_role() <> 'driver' then
    raise exception 'Acceso reservado a conductores autenticados';
  end if;

  select d.id into v_driver_id
  from public.drivers d
  where d.organization_id = v_org_id
    and d.user_id = auth.uid()
  limit 1;

  if v_driver_id is null then
    raise exception 'La cuenta no está vinculada a un perfil de conductor';
  end if;

  if length(trim(coalesce(p_details,''))) < 3 or length(trim(p_details)) > 1500 then
    raise exception 'La descripción debe tener entre 3 y 1500 caracteres';
  end if;

  if p_delivery_id is not null and not exists (
    select 1
    from public.deliveries d
    where d.organization_id = v_org_id
      and d.id = p_delivery_id
      and d.driver_id = v_driver_id
  ) then
    raise exception 'La entrega no está asignada a este conductor';
  end if;

  v_type := coalesce(nullif(trim(p_incident_type),''),'Otro');
  if length(v_type) > 100 then
    raise exception 'El tipo de incidencia supera el límite permitido';
  end if;

  insert into public.driver_incidents(
    organization_id,delivery_id,driver_user_id,incident_type,details
  ) values (
    v_org_id,nullif(p_delivery_id,''),auth.uid(),v_type,trim(p_details)
  ) returning id into v_incident_id;

  return v_incident_id;
end;
$$;

