begin;

-- Requiere el esquema LOGISTEC existente y las migraciones V1.6 y V1.9
-- previamente aplicadas (drivers.user_id, current_user_role y estado de organización).
-- GPS móvil: una jornada pertenece a un conductor autenticado y a un vehículo
-- que ya está asignado a ese conductor dentro de la misma organización.
create table if not exists public.gps_sessions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  driver_id text not null,
  driver_user_id uuid not null references auth.users(id) on delete restrict,
  vehicle_id text not null,
  status text not null default 'active' check (status in ('active','paused','completed')),
  started_at timestamptz not null default now(),
  state_changed_at timestamptz not null default now(),
  ended_at timestamptz,
  device_label text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id,id),
  foreign key (organization_id,driver_id)
    references public.drivers(organization_id,id) on delete restrict,
  foreign key (organization_id,vehicle_id)
    references public.vehicles(organization_id,id) on delete restrict,
  check ((status = 'completed') = (ended_at is not null))
);

create table if not exists public.gps_session_pauses (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  session_id uuid not null,
  paused_at timestamptz not null default now(),
  resumed_at timestamptz,
  created_at timestamptz not null default now(),
  foreign key (organization_id,session_id)
    references public.gps_sessions(organization_id,id) on delete cascade,
  check (resumed_at is null or resumed_at >= paused_at)
);
create index if not exists idx_gps_session_pauses_session_time
  on public.gps_session_pauses(session_id,paused_at,resumed_at);

create unique index if not exists idx_gps_sessions_one_open_per_driver
  on public.gps_sessions(driver_user_id)
  where status in ('active','paused');
create index if not exists idx_gps_sessions_org_state
  on public.gps_sessions(organization_id,status,started_at desc);

alter table public.gps_positions
  add column if not exists session_id uuid,
  add column if not exists driver_id text,
  add column if not exists speed_mps double precision,
  add column if not exists heading_deg double precision,
  add column if not exists client_position_id uuid,
  add column if not exists received_at timestamptz not null default now();

-- Relación aditiva para preservar el historial GPS previo.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'gps_positions_session_org_fk'
      and conrelid = 'public.gps_positions'::regclass
  ) then
    alter table public.gps_positions
      add constraint gps_positions_session_org_fk
      foreign key (organization_id,session_id)
      references public.gps_sessions(organization_id,id)
      on delete set null (session_id);
  end if;
end $$;

create unique index if not exists idx_gps_positions_client_dedupe
  on public.gps_positions(session_id,client_position_id)
  where session_id is not null and client_position_id is not null;
create index if not exists idx_gps_positions_session_time
  on public.gps_positions(session_id,recorded_at asc);

alter table public.gps_sessions enable row level security;
alter table public.gps_session_pauses enable row level security;
alter table public.gps_positions enable row level security;

-- Viewer y conductor solo consultan su propio perfil; el personal operador
-- conserva la consulta de miembros de su misma organización.
drop policy if exists members_select_same_org on public.organization_members;
create policy members_select_same_org on public.organization_members
for select to authenticated
using (
  user_id = auth.uid()
  or (
    organization_id = public.current_org_id()
    and public.current_user_role() in ('owner','admin','dispatcher')
  )
);

-- El perfil de consulta puede revisar incidencias operativas de su empresa,
-- pero la política de UPDATE sigue reservada a owner/admin/dispatcher.
drop policy if exists driver_incidents_select on public.driver_incidents;
create policy driver_incidents_select on public.driver_incidents
for select to authenticated
using (
  organization_id = public.current_org_id()
  and public.current_user_role() in ('owner','admin','dispatcher','viewer')
);

drop policy if exists gps_session_pauses_select on public.gps_session_pauses;
create policy gps_session_pauses_select on public.gps_session_pauses
for select to authenticated
using (
  organization_id = public.current_org_id()
  and (
    public.current_user_role() in ('owner','admin','dispatcher','viewer')
    or exists (
      select 1 from public.gps_sessions s
      where s.id = gps_session_pauses.session_id
        and s.driver_user_id = auth.uid()
    )
  )
);
revoke all on public.gps_session_pauses from anon, authenticated;
grant select on public.gps_session_pauses to authenticated;

-- Lectura: consulta, supervisión y administración solo dentro de su empresa;
-- un conductor solo puede consultar sus propias sesiones y posiciones.
drop policy if exists gps_sessions_select on public.gps_sessions;
create policy gps_sessions_select on public.gps_sessions
for select to authenticated
using (
  organization_id = public.current_org_id()
  and (
    public.current_user_role() in ('owner','admin','dispatcher','viewer')
    or driver_user_id = auth.uid()
  )
);

-- Retira políticas anchas del esquema inicial V1.0 para evitar que políticas
-- permisivas se combinen con las restricciones de V1.6 (PostgreSQL aplica OR).
drop policy if exists vehicles_select_org on public.vehicles;
drop policy if exists drivers_select_org on public.drivers;
drop policy if exists deliveries_select_org on public.deliveries;
drop policy if exists gps_select_org on public.gps_positions;
drop policy if exists gps_positions_access on public.gps_positions;
drop policy if exists gps_positions_select on public.gps_positions;
create policy gps_positions_select on public.gps_positions
for select to authenticated
using (
  organization_id = public.current_org_id()
  and (
    public.current_user_role() in ('owner','admin','dispatcher','viewer')
    or (public.current_user_role() = 'driver' and user_id = auth.uid())
  )
);

-- No se permite insertar posiciones directamente desde el cliente. La escritura
-- pasa obligatoriamente por ingest_gps_position(), que comprueba la jornada.
drop policy if exists gps_positions_insert on public.gps_positions;
drop policy if exists gps_insert_member on public.gps_positions;
revoke insert, update, delete on public.gps_positions from anon, authenticated;
grant select on public.gps_positions to authenticated;
revoke insert, update, delete on public.gps_sessions from anon, authenticated;
grant select on public.gps_sessions to authenticated;

create or replace function public.start_gps_session(
  p_vehicle_id text,
  p_device_label text default ''
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_org uuid := public.current_org_id();
  v_driver_id text;
  v_session_id uuid;
begin
  if v_user is null or v_org is null then
    raise exception 'Debes iniciar sesión en una organización.' using errcode = '42501';
  end if;
  if public.current_user_role() <> 'driver' then
    raise exception 'Solo el conductor asignado puede iniciar su jornada GPS.' using errcode = '42501';
  end if;

  select d.id into v_driver_id
  from public.drivers d
  where d.organization_id = v_org and d.user_id = v_user
  limit 1;
  if v_driver_id is null then
    raise exception 'Tu cuenta no está vinculada a un perfil de conductor.' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.vehicles v
    where v.organization_id = v_org
      and v.id = p_vehicle_id
      and v.driver_id = v_driver_id
      and v.status <> 'En mantenimiento'
  ) then
    raise exception 'El vehículo no está asignado a tu perfil o no está disponible.' using errcode = '42501';
  end if;

  if exists (
    select 1 from public.gps_sessions s
    where s.driver_user_id = v_user and s.status in ('active','paused')
  ) then
    raise exception 'Ya existe una jornada GPS activa o pausada para este conductor.' using errcode = '23505';
  end if;

  insert into public.gps_sessions(
    organization_id,driver_id,driver_user_id,vehicle_id,status,device_label
  ) values (
    v_org,v_driver_id,v_user,p_vehicle_id,'active',left(coalesce(p_device_label,''),120)
  ) returning id into v_session_id;

  return v_session_id;
end;
$$;

create or replace function public.pause_gps_session(p_session_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_session public.gps_sessions%rowtype;
begin
  select * into v_session from public.gps_sessions
  where id = p_session_id
    and organization_id = public.current_org_id()
    and driver_user_id = auth.uid()
  for update;
  if not found then raise exception 'Jornada GPS no encontrada para este conductor.' using errcode = '42501'; end if;
  if v_session.status <> 'active' then raise exception 'La jornada no está activa.'; end if;
  insert into public.gps_session_pauses(organization_id,session_id,paused_at)
  values (v_session.organization_id,p_session_id,now());
  update public.gps_sessions set status='paused',state_changed_at=now(),updated_at=now()
  where id=p_session_id;
  return jsonb_build_object('id',p_session_id,'status','paused');
end;
$$;

create or replace function public.resume_gps_session(p_session_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_session public.gps_sessions%rowtype;
begin
  select * into v_session from public.gps_sessions
  where id = p_session_id
    and organization_id = public.current_org_id()
    and driver_user_id = auth.uid()
  for update;
  if not found then raise exception 'Jornada GPS no encontrada para este conductor.' using errcode = '42501'; end if;
  if v_session.status <> 'paused' then raise exception 'La jornada no está pausada.'; end if;
  update public.gps_session_pauses
  set resumed_at=now()
  where session_id=p_session_id and organization_id=v_session.organization_id and resumed_at is null;
  update public.gps_sessions set status='active',state_changed_at=now(),updated_at=now()
  where id=p_session_id;
  return jsonb_build_object('id',p_session_id,'status','active');
end;
$$;

create or replace function public.finish_gps_session(p_session_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_session public.gps_sessions%rowtype;
begin
  select * into v_session from public.gps_sessions
  where id = p_session_id
    and organization_id = public.current_org_id()
    and driver_user_id = auth.uid()
  for update;
  if not found then raise exception 'Jornada GPS no encontrada para este conductor.' using errcode = '42501'; end if;
  if v_session.status = 'completed' then
    return jsonb_build_object('id',p_session_id,'status','completed','ended_at',v_session.ended_at);
  end if;
  update public.gps_sessions
  set status='completed',ended_at=now(),state_changed_at=now(),updated_at=now()
  where id=p_session_id;
  return jsonb_build_object('id',p_session_id,'status','completed','ended_at',now());
end;
$$;

create or replace function public.ingest_gps_position(
  p_session_id uuid,
  p_client_position_id uuid,
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m double precision,
  p_speed_mps double precision default null,
  p_heading_deg double precision default null,
  p_captured_at timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_org uuid := public.current_org_id();
  v_session public.gps_sessions%rowtype;
  v_position_id bigint;
  v_duplicate boolean := false;
begin
  if v_user is null or v_org is null then
    raise exception 'Sesión no autenticada o sin organización.' using errcode = '42501';
  end if;
  if public.current_user_role() <> 'driver' then
    raise exception 'Solo un conductor puede transmitir una ubicación.' using errcode = '42501';
  end if;
  if p_session_id is null or p_client_position_id is null then
    raise exception 'Falta el identificador de jornada o de posición.';
  end if;
  if p_latitude is null or p_longitude is null
     or p_latitude < -90 or p_latitude > 90
     or p_longitude < -180 or p_longitude > 180 then
    raise exception 'Coordenadas fuera de rango.';
  end if;
  if p_accuracy_m is null or p_accuracy_m <= 0 or p_accuracy_m > 5000 then
    raise exception 'Precisión GPS inválida.';
  end if;
  if p_speed_mps is not null and (p_speed_mps < 0 or p_speed_mps > 90) then
    raise exception 'Velocidad GPS inválida.';
  end if;
  if p_heading_deg is not null and (p_heading_deg < 0 or p_heading_deg >= 360) then
    raise exception 'Dirección GPS inválida.';
  end if;
  if p_captured_at is null
     or p_captured_at > now() + interval '2 minutes'
     or p_captured_at < now() - interval '24 hours' then
    raise exception 'La fecha de captura está fuera de la ventana permitida.';
  end if;

  select * into v_session
  from public.gps_sessions s
  where s.id=p_session_id
    and s.organization_id=v_org
    and s.driver_user_id=v_user
    and s.driver_id = (
      select d.id from public.drivers d
      where d.organization_id=v_org and d.user_id=v_user limit 1
    )
  for update;
  if not found then raise exception 'La jornada GPS no pertenece a este conductor y organización.' using errcode = '42501'; end if;
  if v_session.status = 'completed' and p_captured_at > v_session.ended_at then
    raise exception 'No se aceptan ubicaciones capturadas después de finalizar la jornada.';
  end if;
  if exists (
    select 1 from public.gps_session_pauses p
    where p.session_id=p_session_id
      and p.organization_id=v_org
      and p_captured_at >= p.paused_at
      and p_captured_at < coalesce(p.resumed_at,now())
  ) then
    raise exception 'No se aceptan ubicaciones capturadas durante una pausa de seguimiento.';
  end if;
  if p_captured_at < v_session.started_at - interval '2 minutes' then
    raise exception 'La ubicación es anterior al inicio de la jornada.';
  end if;
  -- Límite del lado servidor para que un cliente modificado no pueda inundar
  -- el historial GPS con puntos separados por menos de ocho segundos.
  if exists (
    select 1 from public.gps_positions p
    where p.session_id = p_session_id
      and p.client_position_id is distinct from p_client_position_id
      and p.recorded_at between p_captured_at - interval '8 seconds'
                            and p_captured_at + interval '8 seconds'
  ) then
    raise exception 'La frecuencia de posiciones GPS excede el límite permitido.' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.vehicles v
    where v.organization_id=v_org and v.id=v_session.vehicle_id
      and v.driver_id=v_session.driver_id
  ) then
    raise exception 'El vehículo ya no está asignado a este conductor.' using errcode = '42501';
  end if;

  select id into v_position_id
  from public.gps_positions
  where session_id=p_session_id and client_position_id=p_client_position_id;
  if found then
    v_duplicate := true;
  else
    insert into public.gps_positions(
      organization_id,vehicle_id,user_id,latitude,longitude,accuracy_m,recorded_at,
      session_id,driver_id,speed_mps,heading_deg,client_position_id,received_at
    ) values (
      v_org,v_session.vehicle_id,v_user,p_latitude,p_longitude,p_accuracy_m,p_captured_at,
      p_session_id,v_session.driver_id,p_speed_mps,p_heading_deg,p_client_position_id,now()
    ) on conflict (session_id,client_position_id) where session_id is not null and client_position_id is not null
      do nothing returning id into v_position_id;
    if v_position_id is null then
      v_duplicate := true;
      select id into v_position_id from public.gps_positions
      where session_id=p_session_id and client_position_id=p_client_position_id;
    end if;

    if not v_duplicate then
    update public.vehicles
    set latitude=p_latitude,
        longitude=p_longitude,
        last_seen=p_captured_at,
        location_mode='real',
        updated_at=now()
    where organization_id=v_org
      and id=v_session.vehicle_id
      and (last_seen is null or last_seen <= p_captured_at);
    end if;
  end if;

  return jsonb_build_object(
    'position_id',v_position_id,
    'session_id',p_session_id,
    'vehicle_id',v_session.vehicle_id,
    'duplicate',v_duplicate,
    'captured_at',p_captured_at
  );
end;
$$;

