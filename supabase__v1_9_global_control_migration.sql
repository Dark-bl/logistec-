-- LOGISTEC V1.9 | Centro Global de Superadministración
-- Ejecutar una sola vez en Supabase SQL Editor después de las migraciones empresariales V1.3, V1.4 y V1.6.
-- No elimina tablas ni datos de la operación actual.
begin;

alter table public.organizations
  add column if not exists platform_status text not null default 'active',
  add column if not exists platform_status_note text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'organizations_platform_status_check'
      and conrelid = 'public.organizations'::regclass
  ) then
    alter table public.organizations
      add constraint organizations_platform_status_check
      check (platform_status in ('active','suspended'));
  end if;
end $$;

create table if not exists public.platform_plans (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (length(trim(code)) between 2 and 40),
  name text not null check (length(trim(name)) between 2 and 100),
  description text not null default '',
  monthly_price numeric(12,2) not null default 0 check (monthly_price >= 0),
  annual_price numeric(12,2) not null default 0 check (annual_price >= 0),
  max_users integer check (max_users is null or max_users > 0),
  max_vehicles integer check (max_vehicles is null or max_vehicles > 0),
  max_deliveries_month integer check (max_deliveries_month is null or max_deliveries_month > 0),
  features jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.platform_subscriptions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null unique references public.organizations(id) on delete cascade,
  plan_id uuid not null references public.platform_plans(id) on delete restrict,
  status text not null default 'trial' check (status in ('trial','active','past_due','suspended','cancelled')),
  monthly_price numeric(12,2) not null default 0 check (monthly_price >= 0),
  starts_at timestamptz not null default now(),
  renews_at timestamptz,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.platform_support_tickets (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations(id) on delete set null,
  subject text not null check (length(trim(subject)) between 3 and 160),
  description text not null default '',
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  status text not null default 'open' check (status in ('open','in_review','resolved','closed')),
  created_by uuid references auth.users(id) on delete set null,
  assigned_to text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.platform_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_email text not null default '',
  action text not null,
  entity_type text not null,
  entity_id text not null default '',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.platform_feature_flags (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  feature_key text not null check (length(trim(feature_key)) between 2 and 80),
  enabled boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (organization_id, feature_key)
);

create table if not exists public.platform_settings (
  setting_key text primary key check (length(trim(setting_key)) between 2 and 100),
  setting_value jsonb not null default 'null'::jsonb,
  description text not null default '',
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create index if not exists idx_platform_subscriptions_status on public.platform_subscriptions(status);
create index if not exists idx_platform_tickets_status on public.platform_support_tickets(status, created_at desc);
create index if not exists idx_platform_audit_created on public.platform_audit_logs(created_at desc);
create index if not exists idx_platform_org_status on public.organizations(platform_status, created_at desc);

-- Tablas privadas: no se exponen por consultas directas del navegador.
alter table public.platform_plans enable row level security;
alter table public.platform_subscriptions enable row level security;
alter table public.platform_support_tickets enable row level security;
alter table public.platform_audit_logs enable row level security;
alter table public.platform_feature_flags enable row level security;
alter table public.platform_settings enable row level security;
revoke all on public.platform_plans, public.platform_subscriptions,
  public.platform_support_tickets, public.platform_audit_logs,
  public.platform_feature_flags, public.platform_settings
  from public, anon, authenticated;

-- Una organización suspendida pierde acceso a los datos operativos por las políticas RLS existentes.
create or replace function public.current_org_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select om.organization_id
  from public.organization_members om
  join public.organizations o on o.id = om.organization_id
  where om.user_id = auth.uid()
    and o.platform_status = 'active'
  limit 1;
$$;

