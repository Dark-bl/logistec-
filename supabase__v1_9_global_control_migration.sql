create or replace function public.get_platform_control_center()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare v_result jsonb;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then
    raise exception 'Acceso reservado al superadministrador de LOGISTEC';
  end if;

  select jsonb_build_object(
    'metrics', jsonb_build_object(
      'organization_count',(select count(*) from public.organizations),
      'active_organization_count',(select count(*) from public.organizations where platform_status='active'),
      'suspended_organization_count',(select count(*) from public.organizations where platform_status='suspended'),
      'member_count',(select count(*) from public.organization_members),
      'vehicle_count',(select count(*) from public.vehicles),
      'delivery_count',(select count(*) from public.deliveries),
      'pending_count',(select count(*) from public.deliveries where status in ('Pendiente','En ruta')),
      'completed_count',(select count(*) from public.deliveries where status='Entregada'),
      'revenue_total',(select coalesce(sum(revenue_amount),0) from public.delivery_financials),
      'expense_total',(select coalesce(sum(amount),0) from public.financial_expenses),
      'active_subscription_count',(select count(*) from public.platform_subscriptions where status='active'),
      'trial_subscription_count',(select count(*) from public.platform_subscriptions where status='trial'),
      'monthly_recurring_revenue',(select coalesce(sum(monthly_price),0) from public.platform_subscriptions where status='active'),
      'open_ticket_count',(select count(*) from public.platform_support_tickets where status in ('open','in_review'))
    ),
    'organizations',(
      select coalesce(jsonb_agg(x.item order by x.created_at desc),'[]'::jsonb)
      from (
        select o.created_at, jsonb_build_object(
          'id',o.id,'name',o.name,'contact_email',o.contact_email,
          'created_at',o.created_at,'platform_status',o.platform_status,
          'platform_status_note',coalesce(o.platform_status_note,''),
          'owner_email',coalesce(u.email,''),
          'member_count',(select count(*) from public.organization_members m where m.organization_id=o.id),
          'vehicle_count',(select count(*) from public.vehicles v where v.organization_id=o.id),
          'delivery_count',(select count(*) from public.deliveries d where d.organization_id=o.id),
          'plan_name',(select p.name from public.platform_subscriptions s join public.platform_plans p on p.id=s.plan_id where s.organization_id=o.id limit 1),
          'subscription_status',(select s.status from public.platform_subscriptions s where s.organization_id=o.id limit 1)
        ) as item
        from public.organizations o
        left join auth.users u on u.id=o.owner_user_id
        order by o.created_at desc limit 500
      ) x
    ),
    'users',(
      select coalesce(jsonb_agg(x.item order by x.organization_name,x.email),'[]'::jsonb)
      from (
        select jsonb_build_object(
          'user_id',u.id,'email',coalesce(u.email,''),'full_name',m.full_name,
          'role',m.role,'organization_id',o.id,'organization_name',o.name,
          'created_at',m.created_at
        ) as item, o.name as organization_name, u.email
        from public.organization_members m
        join auth.users u on u.id=m.user_id
        join public.organizations o on o.id=m.organization_id
        order by o.name,u.email limit 1000
      ) x
    ),
    'plans',(select coalesce(jsonb_agg(to_jsonb(p) order by p.created_at desc),'[]'::jsonb) from public.platform_plans p),
    'subscriptions',(
      select coalesce(jsonb_agg(x.item order by x.updated_at desc),'[]'::jsonb)
      from (
        select s.updated_at,jsonb_build_object(
          'id',s.id,'organization_id',s.organization_id,'organization_name',o.name,
          'plan_id',s.plan_id,'plan_name',p.name,'status',s.status,
          'monthly_price',s.monthly_price,'starts_at',s.starts_at,'renews_at',s.renews_at,'notes',s.notes
        ) as item
        from public.platform_subscriptions s
        join public.organizations o on o.id=s.organization_id
        join public.platform_plans p on p.id=s.plan_id
        order by s.updated_at desc limit 500
      ) x
    ),
    'tickets',(
      select coalesce(jsonb_agg(x.item order by x.created_at desc),'[]'::jsonb)
      from (
        select t.created_at,jsonb_build_object(
          'id',t.id,'organization_id',t.organization_id,
          'organization_name',coalesce(o.name,'Plataforma LOGISTEC'),
          'subject',t.subject,'description',t.description,'priority',t.priority,
          'status',t.status,'assigned_to',t.assigned_to,'created_at',t.created_at,'updated_at',t.updated_at
        ) as item
        from public.platform_support_tickets t
        left join public.organizations o on o.id=t.organization_id
        order by t.created_at desc limit 300
      ) x
    ),
    'audit',(select coalesce(jsonb_agg(to_jsonb(a) order by a.created_at desc),'[]'::jsonb) from (select * from public.platform_audit_logs order by created_at desc limit 300) a),
    'features',(
      select coalesce(jsonb_agg(x.item order by x.organization_name,x.feature_key),'[]'::jsonb)
      from (
        select jsonb_build_object('organization_id',f.organization_id,'organization_name',o.name,'feature_key',f.feature_key,'enabled',f.enabled,'updated_at',f.updated_at) as item,
          o.name as organization_name,f.feature_key
        from public.platform_feature_flags f join public.organizations o on o.id=f.organization_id
      ) x
    ),
    'settings',(select coalesce(jsonb_agg(to_jsonb(s) order by s.setting_key),'[]'::jsonb) from public.platform_settings s)
  ) into v_result;
  return v_result;
end;
$$;

create or replace function public.platform_update_organization_status(p_organization_id uuid,p_status text,p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_name text; v_status text;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if p_status not in ('active','suspended') then raise exception 'Estado no permitido'; end if;
  update public.organizations set platform_status=p_status, platform_status_note=left(coalesce(trim(p_reason),''),500), updated_at=now()
  where id=p_organization_id returning name,platform_status into v_name,v_status;
  if not found then raise exception 'Organización no encontrada'; end if;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'organization_status_changed','organization',p_organization_id::text,jsonb_build_object('status',v_status,'reason',left(coalesce(trim(p_reason),''),500)));
  return jsonb_build_object('id',p_organization_id,'name',v_name,'status',v_status);
end; $$;

create or replace function public.platform_set_member_role(p_organization_id uuid,p_user_id uuid,p_role text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_old_role text; v_org_name text;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if p_role not in ('owner','admin','dispatcher','driver','viewer') then raise exception 'Rol no permitido'; end if;
  select m.role,o.name into v_old_role,v_org_name
  from public.organization_members m join public.organizations o on o.id=m.organization_id
  where m.organization_id=p_organization_id and m.user_id=p_user_id;
  if not found then raise exception 'No existe esa membresía'; end if;
  if v_old_role='owner' and p_role<>'owner' and (select count(*) from public.organization_members where organization_id=p_organization_id and role='owner')<=1 then
    raise exception 'No puedes quitar el único propietario de la empresa';
  end if;
  update public.organization_members set role=p_role where organization_id=p_organization_id and user_id=p_user_id;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'member_role_changed','organization_member',p_user_id::text,jsonb_build_object('organization_id',p_organization_id,'organization',v_org_name,'old_role',v_old_role,'new_role',p_role));
  return jsonb_build_object('user_id',p_user_id,'role',p_role);
end; $$;

create or replace function public.platform_save_plan(p_plan_id uuid,p_code text,p_name text,p_description text,p_monthly_price numeric,p_annual_price numeric,p_max_users integer,p_max_vehicles integer,p_max_deliveries_month integer,p_features jsonb,p_is_active boolean)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_id uuid;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if length(trim(coalesce(p_code,''))) not between 2 and 40 or length(trim(coalesce(p_name,''))) not between 2 and 100 then raise exception 'Código o nombre de plan inválido'; end if;
  if coalesce(p_monthly_price,-1)<0 or coalesce(p_annual_price,-1)<0 then raise exception 'Los precios no pueden ser negativos'; end if;
  if p_plan_id is null then
    insert into public.platform_plans(code,name,description,monthly_price,annual_price,max_users,max_vehicles,max_deliveries_month,features,is_active)
    values(lower(trim(p_code)),trim(p_name),left(coalesce(p_description,''),1000),p_monthly_price,p_annual_price,p_max_users,p_max_vehicles,p_max_deliveries_month,coalesce(p_features,'{}'::jsonb),coalesce(p_is_active,true)) returning id into v_id;
  else
    update public.platform_plans set code=lower(trim(p_code)),name=trim(p_name),description=left(coalesce(p_description,''),1000),monthly_price=p_monthly_price,annual_price=p_annual_price,max_users=p_max_users,max_vehicles=p_max_vehicles,max_deliveries_month=p_max_deliveries_month,features=coalesce(p_features,'{}'::jsonb),is_active=coalesce(p_is_active,true),updated_at=now()
    where id=p_plan_id returning id into v_id;
    if v_id is null then raise exception 'Plan no encontrado'; end if;
  end if;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'plan_saved','plan',v_id::text,jsonb_build_object('code',lower(trim(p_code)),'name',trim(p_name),'active',coalesce(p_is_active,true)));
  return v_id;
end; $$;

create or replace function public.platform_upsert_subscription(p_organization_id uuid,p_plan_id uuid,p_status text,p_renews_at timestamptz,p_notes text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_id uuid; v_price numeric;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if p_status not in ('trial','active','past_due','suspended','cancelled') then raise exception 'Estado de suscripción no permitido'; end if;
  select monthly_price into v_price from public.platform_plans where id=p_plan_id and is_active=true;
  if v_price is null then raise exception 'El plan no existe o está inactivo'; end if;
  insert into public.platform_subscriptions(organization_id,plan_id,status,monthly_price,renews_at,notes)
  values(p_organization_id,p_plan_id,p_status,v_price,p_renews_at,left(coalesce(p_notes,''),1000))
  on conflict(organization_id) do update set plan_id=excluded.plan_id,status=excluded.status,monthly_price=excluded.monthly_price,renews_at=excluded.renews_at,notes=excluded.notes,updated_at=now()
  returning id into v_id;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'subscription_updated','subscription',v_id::text,jsonb_build_object('organization_id',p_organization_id,'plan_id',p_plan_id,'status',p_status,'monthly_price',v_price));
  return v_id;
end; $$;

create or replace function public.platform_create_support_ticket(p_organization_id uuid,p_subject text,p_description text,p_priority text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_id uuid;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if length(trim(coalesce(p_subject,''))) not between 3 and 160 then raise exception 'El asunto debe tener entre 3 y 160 caracteres'; end if;
  if p_priority not in ('low','normal','high','urgent') then raise exception 'Prioridad no permitida'; end if;
  if p_organization_id is not null and not exists(select 1 from public.organizations where id=p_organization_id) then raise exception 'Organización no encontrada'; end if;
  insert into public.platform_support_tickets(organization_id,subject,description,priority,created_by)
  values(p_organization_id,trim(p_subject),left(coalesce(p_description,''),5000),p_priority,auth.uid()) returning id into v_id;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'support_ticket_created','support_ticket',v_id::text,jsonb_build_object('subject',trim(p_subject),'priority',p_priority));
  return v_id;
end; $$;

create or replace function public.platform_update_support_ticket(p_ticket_id uuid,p_status text,p_assigned_to text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_row public.platform_support_tickets%rowtype;
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if p_status not in ('open','in_review','resolved','closed') then raise exception 'Estado no permitido'; end if;
  update public.platform_support_tickets set status=p_status,assigned_to=nullif(left(trim(coalesce(p_assigned_to,'')),120),''),updated_at=now(),resolved_at=case when p_status in ('resolved','closed') then coalesce(resolved_at,now()) else null end
  where id=p_ticket_id returning * into v_row;
  if not found then raise exception 'Ticket no encontrado'; end if;
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'support_ticket_updated','support_ticket',p_ticket_id::text,jsonb_build_object('status',p_status,'assigned_to',v_row.assigned_to));
  return jsonb_build_object('id',v_row.id,'status',v_row.status);
end; $$;

create or replace function public.platform_set_feature_flag(p_organization_id uuid,p_feature_key text,p_enabled boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if not exists(select 1 from public.organizations where id=p_organization_id) then raise exception 'Organización no encontrada'; end if;
  if length(trim(coalesce(p_feature_key,''))) not between 2 and 80 then raise exception 'Clave de función inválida'; end if;
  insert into public.platform_feature_flags(organization_id,feature_key,enabled,updated_by)
  values(p_organization_id,lower(trim(p_feature_key)),p_enabled,auth.uid())
  on conflict(organization_id,feature_key) do update set enabled=excluded.enabled,updated_by=auth.uid(),updated_at=now();
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'feature_flag_changed','feature_flag',p_organization_id::text,jsonb_build_object('feature_key',lower(trim(p_feature_key)),'enabled',p_enabled));
  return jsonb_build_object('organization_id',p_organization_id,'feature_key',lower(trim(p_feature_key)),'enabled',p_enabled);
end; $$;

create or replace function public.platform_save_setting(p_key text,p_value jsonb,p_description text)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or not public.is_platform_superadmin() then raise exception 'Acceso denegado'; end if;
  if p_key !~ '^[a-zA-Z][a-zA-Z0-9_.-]{1,99}$' then raise exception 'Clave de configuración inválida'; end if;
  insert into public.platform_settings(setting_key,setting_value,description,updated_by)
  values(p_key,p_value,left(coalesce(p_description,''),500),auth.uid())
  on conflict(setting_key) do update set setting_value=excluded.setting_value,description=excluded.description,updated_by=auth.uid(),updated_at=now();
  insert into public.platform_audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
  values(auth.uid(),coalesce((select email from auth.users where id=auth.uid()),''),'platform_setting_saved','platform_setting',p_key,jsonb_build_object('description',left(coalesce(p_description,''),500)));
  return jsonb_build_object('key',p_key,'saved',true);
end; $$;

